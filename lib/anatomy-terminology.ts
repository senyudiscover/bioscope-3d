export function normalizeAnatomyName(name: string) {
  return name
    .replace(/[()[\]{}*_]/g, " ")
    .replace(/[._,/\\-]+/g, " ")
    .replace(/\b(right|left)\b/gi, "$1")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

